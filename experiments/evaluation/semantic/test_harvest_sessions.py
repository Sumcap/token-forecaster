def claude_transcript():
    """A two-turn transcript in the shape Claude Code writes.

    The second call answers a tool_result, so the loader must place it in the
    same turn as the first; the third is preceded by a real user message, so it
    must open a new one.
    """
    def assistant(uuid, parent, request, tokens, blocks, stop, ts):
        return {
            "type": "assistant",
            "uuid": uuid,
            "parentUuid": parent,
            "requestId": request,
            "sessionId": "s1",
            "timestamp": ts,
            "message": {
                "model": "claude-sonnet-4-5-20260101",
                "stop_reason": stop,
                "usage": {"output_tokens": tokens},
                "content": blocks,
            },
        }

    return [
        {
            "type": "user",
            "uuid": "u1",
            "parentUuid": None,
            "sessionId": "s1",
            "timestamp": "2026-01-01T09:00:00.000Z",
            "message": {"role": "user", "content": "please refactor the loader"},
        },
        assistant(
            "a1",
            "u1",
            "req_1",
            140,
            [
                {"type": "text", "text": "Reading it."},
                {"type": "tool_use", "name": "Read", "input": {"file_path": "/x/loader.py"}},
            ],
            "tool_use",
            "2026-01-01T09:00:05.000Z",
        ),
        {
            "type": "user",
            "uuid": "u2",
            "parentUuid": "a1",
            "sessionId": "s1",
            "timestamp": "2026-01-01T09:00:06.000Z",
            "message": {
                "role": "user",
                "content": [{"type": "tool_result", "content": "the file body"}],
            },
        },
        assistant(
            "a2",
            "u2",
            "req_2",
            900,
            [
                {"type": "thinking", "thinking": "considering the edit"},
                {"type": "tool_use", "name": "Edit", "input": {"new_string": "y" * 400}},
            ],
            "end_turn",
            "2026-01-01T09:00:09.000Z",
        ),
        {
            "type": "user",
            "uuid": "u3",
            "parentUuid": "a2",
            "sessionId": "s1",
            "timestamp": "2026-01-01T09:01:00.000Z",
            "message": {"role": "user", "content": "now run the tests"},
        },
        assistant(
            "a3",
            "u3",
            "req_3",
            60,
            [{"type": "text", "text": "Running them."}],
            "end_turn",
            "2026-01-01T09:01:03.000Z",
        ),
    ]


@pytest.mark.skipif(shutil.which("node") is None, reason="node is required")
def test_claude_code_turn_and_call_cutting_through_the_shipped_loader(tmp_path):
    sha = "a" * 40
    staging = tmp_path / "staging" / sha
    staging.mkdir(parents=True)
    (staging / f"{sha}.jsonl").write_text(
        "\n".join(json.dumps(row) for row in claude_transcript()) + "\n"
    )
    out = tmp_path / "calls.jsonl"
    proc = subprocess.run(
        [
            "node",
            str(HERE / "claude_calls.mjs"),
            "--staging",
            str(tmp_path / "staging"),
            "--out",
            str(out),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    calls = [json.loads(line) for line in out.read_text().splitlines() if line.strip()]
    assert len(calls) == 3
    by_id = {c["requestId"]: c for c in calls}
    # native usage, verbatim
    assert [by_id[f"req_{i}"]["outputTokens"] for i in (1, 2, 3)] == [140, 900, 60]
    # two calls in the first turn, one in the second
    assert by_id["req_1"]["turnRootId"] == by_id["req_2"]["turnRootId"] == "u1"
    assert by_id["req_3"]["turnRootId"] == "u3"
    assert by_id["req_2"]["loopDepth"] == 1
    assert by_id["req_1"]["tools"] == ["Read"]
    assert by_id["req_2"]["largestToolInputChars"] > 400
    assert by_id["req_1"]["stopReason"] == "tool_use"
    assert by_id["req_2"]["thinking"] == "yes"
    # the turn-root prompt is inherited by every call in the turn
    assert by_id["req_2"]["turnPromptText"] == "please refactor the loader"

    stats: Counter = Counter()
    turns = list(claude_sessions(calls, {sha: "owner/repo"}, stats))
    assert [t["turn_index"] for t in turns] == [0, 1]
    assert [len(t["calls"]) for t in turns] == [2, 1]
    assert turns[0]["user"] == "owner/repo"
    assert turns[0]["session"] == f"claude-code:{sha}"
    assert all(t["exact"] for t in turns)


