def test_emit_writes_prompt_text_on_the_turn_root_only_and_sums_the_turn():
    calls_out: list[dict] = []
    turns_out: list[dict] = []
    stats: Counter = Counter()
    emit(
        {
            "source": "cline-task",
            "user": "owner/repo",
            "session": "cline-task:k",
            "turn_index": 0,
            "turn_root_id": "k:0",
            "text": "  add caching  ",
            "calls": [
                {
                    "model": None,
                    "output_tokens": 40,
                    "usage_source": "native:cline",
                    "tool_names": ["read_file"],
                    "largest_tool_input_chars": 12,
                    "stop_reason": None,
                },
                {
                    "model": None,
                    "output_tokens": None,
                    "usage_source": None,
                    "visible_text": "some visible reply text",
                    "tool_names": None,
                    "largest_tool_input_chars": None,
                    "stop_reason": None,
                },
            ],
        },
        {"owner/repo": "MIT"},
        calls_out,
        turns_out,
        Estimator(),
        stats,
    )
    assert len(calls_out) == 2 and len(turns_out) == 1
    assert calls_out[0]["text"] == "add caching"
    assert calls_out[0]["prompt_chars"] == len("add caching")
    # only the turn root carries text
    assert calls_out[1]["text"] is None and calls_out[1]["prompt_chars"] is None
    assert calls_out[0]["visible_text_only"] is False
    # the estimated call is flagged as visible text only
    assert calls_out[1]["usage_source"] == "estimated"
    assert calls_out[1]["visible_text_only"] is True
    assert calls_out[1]["output_tokens"] > 0
    assert [c["call_index"] for c in calls_out] == [0, 1]
    turn = turns_out[0]
    assert turn["calls"] == 2
    assert turn["output_tokens"] == sum(c["output_tokens"] for c in calls_out)
    assert turn["usage_source"] == "mixed"
    assert turn["visible_text_only"] is False
    assert turn["license"] == "MIT"


