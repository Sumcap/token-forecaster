def test_aider_turns_calls_and_native_usage():
    turns = list(markdown_turns("aider", AIDER))
    assert len(turns) == 3
    assert turns[0]["text"] == "add a health check to the server"
    # aider answers a turn with exactly one model response
    assert [len(t["blocks"]) for t in turns] == [1, 1, 1]
    # the console line is NOT model output
    assert "Applied edit to server.py" not in turns[0]["blocks"][0]
    # the fenced code IS model output
    assert "healthz" in turns[0]["blocks"][0]
    assert turns[0]["native"] == 1100
    assert turns[1]["native"] == 512
    assert turns[2]["native"] is None
    # the second `# aider chat started` opens a new session
    assert turns[0]["session_part"] == turns[1]["session_part"] == 1
    assert turns[2]["session_part"] == 2
    assert turns[0]["model"] == "gpt-4o"


