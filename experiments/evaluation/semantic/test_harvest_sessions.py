def cline_history():
    return [
        {"role": "user", "content": [{"type": "text", "text": "<task>add caching</task>"}]},
        {
            "role": "assistant",
            "content": [
                {"type": "text", "text": "Let me look at the file."},
                {"type": "tool_use", "name": "read_file", "input": {"path": "a.py"}},
            ],
        },
        {
            "role": "user",
            "content": [
                {"type": "tool_result", "content": "file body"},
                {"type": "text", "text": "<environment_details>noise</environment_details>"},
            ],
        },
        {
            "role": "assistant",
            "content": [
                {"type": "text", "text": "<write_to_file>\n<path>a.py</path>\n<content>"
                 + "x" * 200 + "</content>\n</write_to_file>"}
            ],
        },
        {"role": "user", "content": [{"type": "text", "text": "<feedback>also add a test</feedback>"}]},
        {"role": "assistant", "content": [{"type": "text", "text": "Adding the test."}]},
    ]


def ui(*payloads):
    return [{"type": "say", "say": "api_req_started", "text": json.dumps(p)} for p in payloads]


def test_cline_task_turns_calls_and_native_usage():
    stats: Counter = Counter()
    messages = ui(
        {"tokensIn": 100, "tokensOut": 40},
        {"tokensIn": 200, "tokensOut": 900},
        {"tokensIn": 300, "tokensOut": 55},
    )
    turns, aligned = parse_cline_task(cline_history(), messages, stats)
    assert aligned is True
    # <task> and <feedback> are turn roots; the tool-result user row is not
    assert [t["text"] for t in turns] == ["add caching", "also add a test"]
    assert [len(t["calls"]) for t in turns] == [2, 1]
    assert [c["output_tokens"] for c in turns[0]["calls"]] == [40, 900]
    assert turns[1]["calls"][0]["output_tokens"] == 55
    # native tool_use blocks and XML-in-text tool calls are both recognised
    assert turns[0]["calls"][0]["tools"] == ["read_file"]
    assert turns[0]["calls"][1]["tools"] == ["write_to_file"]
    assert turns[0]["calls"][1]["largest"] > 200


def test_cline_task_trailing_in_flight_request_still_aligns():
    stats: Counter = Counter()
    messages = ui(
        {"tokensOut": 40},
        {"tokensOut": 900},
        {"tokensOut": 55},
        {"request": "still running"},  # committed mid-request
    )
    _turns, aligned = parse_cline_task(cline_history(), messages, stats)
    assert aligned is True


def test_cline_task_missing_usage_keeps_its_slot():
    stats: Counter = Counter()
    messages = ui(
        {"tokensOut": 40},
        {"usageMissing": True, "tokensOut": 0},
        {"tokensOut": 55},
    )
    turns, aligned = parse_cline_task(cline_history(), messages, stats)
    assert aligned is True
    # the failed request does not shift the counts of the calls after it
    assert turns[0]["calls"][0]["output_tokens"] == 40
    assert turns[0]["calls"][1]["output_tokens"] is None
    assert turns[1]["calls"][0]["output_tokens"] == 55


def test_cline_task_misaligned_usage_is_refused_wholesale():
    stats: Counter = Counter()
    turns, aligned = parse_cline_task(cline_history(), ui({"tokensOut": 40}), stats)
    assert aligned is False
    assert stats["cline:usage-misaligned"] == 1
    assert all(c["output_tokens"] is None for t in turns for c in t["calls"])


