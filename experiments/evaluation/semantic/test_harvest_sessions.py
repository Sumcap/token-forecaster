def codex_rows():
    def token_count(output, reasoning, total):
        return {
            "type": "event_msg",
            "payload": {
                "type": "token_count",
                "info": {
                    "last_token_usage": {
                        "input_tokens": 10,
                        "output_tokens": output,
                        "reasoning_output_tokens": reasoning,
                    },
                    "total_token_usage": {"total_tokens": total},
                },
            },
        }

    return [
        {"type": "session_meta", "payload": {"id": "abc", "cli_version": "0.30.0"}},
        {"type": "turn_context", "payload": {"model": "gpt-5-2-codex", "effort": "high"}},
        {"type": "event_msg", "payload": {"type": "user_message", "message": "port the CLI to windows"}},
        {"type": "response_item", "payload": {"type": "function_call", "name": "shell"}},
        token_count(120, 80, 500),
        token_count(120, 80, 500),  # the CLI re-emits for UI refreshes
        {"type": "response_item", "payload": {"type": "function_call", "name": "apply_patch"}},
        token_count(300, 200, 900),
        {"type": "event_msg", "payload": {"type": "user_message", "message": "now the tests"}},
        token_count(70, 0, 1000),
    ]


def test_codex_turns_calls_dedupe_and_reasoning():
    stats: Counter = Counter()
    text = "\n".join(json.dumps(row) for row in codex_rows())
    turns = parse_codex(text, stats)
    assert [t["text"] for t in turns] == ["port the CLI to windows", "now the tests"]
    assert [len(t["calls"]) for t in turns] == [2, 1]
    assert [c["output_tokens"] for c in turns[0]["calls"]] == [120, 300]
    assert [c["reasoning_tokens"] for c in turns[0]["calls"]] == [80, 200]
    assert turns[0]["calls"][0]["tools"] == ["shell"]
    assert turns[0]["calls"][1]["tools"] == ["apply_patch"]
    assert turns[0]["calls"][0]["model"] == "gpt-5-2-codex"


